import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1512, height: 982 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(process.env.TEST_URL || 'http://localhost:5173/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Begin traverse', exact: false }).waitFor();
await page.waitForFunction(() => document.documentElement.dataset.terrainReady === 'true' && !document.querySelector('.loading-screen'));
await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
console.log(JSON.stringify({ errors, route: await page.locator('.route-stats').innerText(), verdict: await page.locator('.route-verdict').innerText(), canvas: await page.locator('canvas').count() }, null, 2));
await browser.close();
